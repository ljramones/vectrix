package org.dynamisengine.vectrix.fft;

import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;

/**
 * A precomputed plan for the discrete Fourier transform of {@code n} complex values, for any {@code n}.
 * <p>
 * Data is interleaved: {@code data[off + 2k]} is the real part of element {@code k} and {@code data[off + 2k + 1]}
 * its imaginary part. {@link #forward} computes {@code X[k] = Σ x[j]·exp(-2πi jk/n)}, unscaled; {@link #inverse}
 * uses {@code exp(+2πi jk/n)} and divides by {@code n}, so {@code inverse(forward(x)) = x}.
 * <p>
 * <b>Algorithm.</b> Sizes whose prime factors are at most 61 use a self-sorting (Stockham) mixed-radix transform
 * with radix-4, 2, 3 and 5 butterflies and a direct butterfly for other primes. Other sizes use Bluestein's
 * algorithm over a power-of-two transform. Every twiddle factor is precomputed with exact argument reduction
 * (within about one ulp), and none is generated by recurrence, so the error grows only with {@code log n}. The
 * measured relative RMS error against an exact DFT is below {@code 6e-16} for every size tested, up to
 * {@code 2^22}.
 * <p>
 * <b>Threads and memory.</b> A plan is immutable once created, and one instance can be shared by any number of
 * threads. The transforms keep no state and do not allocate: each call takes a caller-owned scratch array of at
 * least {@link #scratchSize()} values (one per thread), which it overwrites. Results are deterministic: the same
 * inputs give the same bits on every platform under {@code -Dvectrix.strictMath=true} (which also fixes the
 * twiddles), independently of the thread count.
 *
 * @since 2.5.0
 */
public final class ComplexFftd {

    /** The largest supported size. Sizes that need Bluestein's algorithm are limited to {@code 2^27}. */
    public static final int MAX_SIZE = 1 << 28;

    private final int n;
    private final int[] radix;
    private final double[][] twiddle;
    private final double[][] primeRoots;
    private final int tempSize;
    private final double c3;
    private final double c51;
    private final double c52;
    private final double s51;
    private final double s52;
    // Bluestein's algorithm
    private final ComplexFftd inner;
    private final double[] chirp;
    private final double[] kernel;
    private final int scratchSize;

    private ComplexFftd(int n) {
        this.n = n;
        double[] r = new double[2];
        FftMath.root(1, 12, r, 0); // exp(-iπ/6): sin(π/3) is its real part
        c3 = r[0];
        FftMath.root(1, 5, r, 0);
        c51 = r[0];
        s51 = -r[1];
        FftMath.root(2, 5, r, 0);
        c52 = r[0];
        s52 = -r[1];
        int[] f = FftMath.factor(n);
        if (f.length == 0 || f[f.length - 1] <= FftMath.MAX_DIRECT_PRIME) {
            radix = f;
            twiddle = new double[f.length][];
            primeRoots = new double[f.length][];
            int len = n;
            int maxPrime = 0;
            for (int i = 0; i < f.length; i++) {
                int p = f[i];
                int m = len / p;
                // stage twiddles W_len^(j·q) for q < m, 1 <= j < p, as powers of the root of order n
                double[] t = new double[2 * m * (p - 1)];
                long step = n / len;
                for (int q = 0; q < m; q++) {
                    for (int j = 1; j < p; j++) {
                        FftMath.root(step * j * q, n, t, 2 * (q * (p - 1) + j - 1));
                    }
                }
                twiddle[i] = t;
                if (p > 5) {
                    primeRoots[i] = FftMath.roots(p, p);
                    maxPrime = java.lang.Math.max(maxPrime, p);
                }
                len = m;
            }
            tempSize = 4 * maxPrime;
            inner = null;
            chirp = null;
            kernel = null;
            scratchSize = 2 * n + tempSize;
        } else {
            if (n > (1 << 27)) {
                throw new IllegalArgumentException("sizes with a prime factor above " + FftMath.MAX_DIRECT_PRIME
                        + " are limited to 2^27: " + n);
            }
            int m = Integer.highestOneBit(2 * n - 1) << 1;
            radix = null;
            twiddle = null;
            primeRoots = null;
            tempSize = 0;
            inner = new ComplexFftd(m);
            // chirp w_j = exp(-iπ j²/n) = exp(-2πi j²/(2n)), with j² reduced exactly
            chirp = new double[2 * n];
            long d = 2L * n;
            for (int j = 0; j < n; j++) {
                FftMath.root(((long) j * j) % d, d, chirp, 2 * j);
            }
            // kernel b_k = conj(w_|k|) on the circle of length m, transformed and divided by m
            kernel = new double[2 * m];
            for (int j = 0; j < n; j++) {
                kernel[2 * j] = chirp[2 * j];
                kernel[2 * j + 1] = -chirp[2 * j + 1];
                if (j > 0) {
                    kernel[2 * (m - j)] = chirp[2 * j];
                    kernel[2 * (m - j) + 1] = -chirp[2 * j + 1];
                }
            }
            double[] s = new double[inner.scratchSize];
            inner.run(kernel, 0, s, 0, false);
            for (int i = 0; i < kernel.length; i++) {
                kernel[i] /= m; // a power of two: exact
            }
            scratchSize = 2 * m + inner.scratchSize;
        }
    }

    /**
     * Creates a plan for {@code n} complex values.
     *
     * @param n the transform size, {@code 1 <= n <= MAX_SIZE}
     * @return the plan
     * @throws IllegalArgumentException if {@code n} is out of range
     */
    public static ComplexFftd plan(int n) {
        if (n < 1 || n > MAX_SIZE) {
            throw new IllegalArgumentException("size must be in [1, 2^28]: " + n);
        }
        return new ComplexFftd(n);
    }

    /**
     * The smallest size of at least {@code min} whose prime factors are 2, 3 and 5: the sizes this plan transforms
     * fastest. Padding to it is the usual choice for convolution and spectral analysis.
     *
     * @param min the minimum size, {@code 1 <= min <= MAX_SIZE}
     * @return the fast size
     */
    public static int fastSize(int min) {
        if (min < 1 || min > MAX_SIZE) {
            throw new IllegalArgumentException("size must be in [1, 2^28]: " + min);
        }
        long best = Long.highestOneBit(min) == min ? min : Long.highestOneBit(min) << 1;
        for (long p5 = 1; p5 < best; p5 *= 5) {
            for (long p35 = p5; p35 < best; p35 *= 3) {
                long v = p35;
                while (v < min) {
                    v <<= 1;
                }
                best = java.lang.Math.min(best, v);
            }
        }
        return (int) best;
    }

    /** @return the number of complex values transformed */
    public int size() {
        return n;
    }

    /** @return the number of doubles the scratch array needs for the array overloads */
    public int scratchSize() {
        return scratchSize;
    }

    /** @return the number of doubles the scratch array needs for the {@link MemorySegment} overloads */
    public long segmentScratchSize() {
        return 2L * n + scratchSize;
    }

    /**
     * Transforms {@code data[off .. off + 2n)} in place.
     *
     * @param data the interleaved complex values
     * @param off the offset of the first value
     * @param scratch caller-owned working memory of at least {@link #scratchSize()} doubles
     * @param scratchOff the offset into {@code scratch}
     */
    public void forward(double[] data, int off, double[] scratch, int scratchOff) {
        check(data, off, scratch, scratchOff, scratchSize);
        run(data, off, scratch, scratchOff, false);
    }

    /**
     * Inverse-transforms {@code data[off .. off + 2n)} in place, dividing by {@code n}.
     *
     * @param data the interleaved complex values
     * @param off the offset of the first value
     * @param scratch caller-owned working memory of at least {@link #scratchSize()} doubles
     * @param scratchOff the offset into {@code scratch}
     */
    public void inverse(double[] data, int off, double[] scratch, int scratchOff) {
        check(data, off, scratch, scratchOff, scratchSize);
        run(data, off, scratch, scratchOff, true);
        scale(data, off);
    }

    /**
     * Transforms {@code 2n} native-order doubles at the start of {@code data} in place.
     *
     * @param data the interleaved complex values, at least {@code 16n} bytes
     * @param scratch caller-owned working memory of at least {@link #segmentScratchSize()} doubles
     */
    public void forward(MemorySegment data, double[] scratch) {
        segment(data, scratch, false);
    }

    /**
     * Inverse-transforms {@code 2n} native-order doubles at the start of {@code data} in place, dividing by
     * {@code n}.
     *
     * @param data the interleaved complex values, at least {@code 16n} bytes
     * @param scratch caller-owned working memory of at least {@link #segmentScratchSize()} doubles
     */
    public void inverse(MemorySegment data, double[] scratch) {
        segment(data, scratch, true);
    }

    private void segment(MemorySegment data, double[] scratch, boolean inv) {
        if (data == null || data.byteSize() < 16L * n) {
            throw new IllegalArgumentException("data must hold " + 2L * n + " doubles");
        }
        if (scratch == null || scratch.length < segmentScratchSize()) {
            throw new IllegalArgumentException("scratch must hold " + segmentScratchSize() + " doubles");
        }
        MemorySegment.copy(data, ValueLayout.JAVA_DOUBLE_UNALIGNED, 0, scratch, 0, 2 * n);
        run(scratch, 0, scratch, 2 * n, inv);
        if (inv) {
            scale(scratch, 0);
        }
        MemorySegment.copy(scratch, 0, data, ValueLayout.JAVA_DOUBLE_UNALIGNED, 0, 2 * n);
    }

    private void check(double[] data, int off, double[] scratch, int scratchOff, int need) {
        if (data == null || off < 0 || off > data.length - 2 * n) {
            throw new IllegalArgumentException("data must hold " + 2L * n + " doubles from offset " + off);
        }
        if (scratch == null || scratchOff < 0 || scratchOff > scratch.length - need) {
            throw new IllegalArgumentException("scratch must hold " + need + " doubles from offset " + scratchOff);
        }
    }

    private void scale(double[] d, int off) {
        if (FftMath.isPowerOfTwo(n)) {
            double s = 1.0 / n; // exact
            for (int i = off, e = off + 2 * n; i < e; i++) {
                d[i] *= s;
            }
        } else {
            double s = n;
            for (int i = off, e = off + 2 * n; i < e; i++) {
                d[i] /= s; // correctly rounded
            }
        }
    }

    /** The unscaled transform; {@code inv} conjugates the roots. */
    void run(double[] d, int off, double[] s, int soff, boolean inv) {
        if (inner != null) {
            bluestein(d, off, s, soff, inv);
            return;
        }
        double sg = inv ? -1.0 : 1.0;
        double[] src = d;
        int so = off;
        double[] dst = s;
        int dso = soff;
        int stride = 1;
        int len = n;
        int temp = soff + 2 * n;
        for (int i = 0; i < radix.length; i++) {
            int p = radix[i];
            int m = len / p;
            double[] tw = twiddle[i];
            switch (p) {
                case 4: radix4(src, so, dst, dso, m, stride, tw, sg); break;
                case 2: radix2(src, so, dst, dso, m, stride, tw, sg); break;
                case 3: radix3(src, so, dst, dso, m, stride, tw, sg); break;
                case 5: radix5(src, so, dst, dso, m, stride, tw, sg); break;
                default: radixP(src, so, dst, dso, p, m, stride, tw, primeRoots[i], sg, s, temp); break;
            }
            double[] ta = src;
            src = dst;
            dst = ta;
            int to = so;
            so = dso;
            dso = to;
            stride *= p;
            len = m;
        }
        if (src != d || so != off) {
            System.arraycopy(src, so, d, off, 2 * n);
        }
    }

    private void bluestein(double[] d, int off, double[] s, int soff, boolean inv) {
        int m = inner.n;
        double sg = inv ? -1.0 : 1.0;
        // a_j = x_j·w_j (conjugated chirp for the inverse), zero-padded to m
        for (int j = 0; j < n; j++) {
            double xr = d[off + 2 * j];
            double xi = d[off + 2 * j + 1];
            double wr = chirp[2 * j];
            double wi = sg * chirp[2 * j + 1];
            s[soff + 2 * j] = xr * wr - xi * wi;
            s[soff + 2 * j + 1] = xr * wi + xi * wr;
        }
        java.util.Arrays.fill(s, soff + 2 * n, soff + 2 * m, 0.0);
        int inScratch = soff + 2 * m;
        inner.run(s, soff, s, inScratch, false);
        // the kernel is symmetric, so the inverse uses its conjugate
        for (int k = 0; k < m; k++) {
            int o = soff + 2 * k;
            double ar = s[o];
            double ai = s[o + 1];
            double br = kernel[2 * k];
            double bi = sg * kernel[2 * k + 1];
            s[o] = ar * br - ai * bi;
            s[o + 1] = ar * bi + ai * br;
        }
        inner.run(s, soff, s, inScratch, true);
        for (int k = 0; k < n; k++) {
            double cr = s[soff + 2 * k];
            double ci = s[soff + 2 * k + 1];
            double wr = chirp[2 * k];
            double wi = sg * chirp[2 * k + 1];
            d[off + 2 * k] = cr * wr - ci * wi;
            d[off + 2 * k + 1] = cr * wi + ci * wr;
        }
    }

    // Stockham stages. Input element (q, k) is at q + stride·(p + k·m); output (q, j) at q + stride·(r·p + j);
    // output j is multiplied by the twiddle W_len^(j·p).

    private static void radix2(double[] x, int xo, double[] y, int yo, int m, int stride, double[] tw, double sg) {
        for (int p = 0; p < m; p++) {
            double w1r = tw[2 * p];
            double w1i = sg * tw[2 * p + 1];
            int a0 = xo + 2 * stride * p;
            int a1 = a0 + 2 * stride * m;
            int b0 = yo + 2 * stride * 2 * p;
            int b1 = b0 + 2 * stride;
            for (int q = 0; q < 2 * stride; q += 2) {
                double x0r = x[a0 + q];
                double x0i = x[a0 + q + 1];
                double x1r = x[a1 + q];
                double x1i = x[a1 + q + 1];
                y[b0 + q] = x0r + x1r;
                y[b0 + q + 1] = x0i + x1i;
                double dr = x0r - x1r;
                double di = x0i - x1i;
                y[b1 + q] = dr * w1r - di * w1i;
                y[b1 + q + 1] = dr * w1i + di * w1r;
            }
        }
    }

    private static void radix4(double[] x, int xo, double[] y, int yo, int m, int stride, double[] tw, double sg) {
        int sm = 2 * stride * m;
        for (int p = 0; p < m; p++) {
            int t = 6 * p;
            double w1r = tw[t];
            double w1i = sg * tw[t + 1];
            double w2r = tw[t + 2];
            double w2i = sg * tw[t + 3];
            double w3r = tw[t + 4];
            double w3i = sg * tw[t + 5];
            int a0 = xo + 2 * stride * p;
            int b0 = yo + 2 * stride * 4 * p;
            int bs = 2 * stride;
            for (int q = 0; q < 2 * stride; q += 2) {
                int i0 = a0 + q;
                double x0r = x[i0];
                double x0i = x[i0 + 1];
                double x1r = x[i0 + sm];
                double x1i = x[i0 + sm + 1];
                double x2r = x[i0 + 2 * sm];
                double x2i = x[i0 + 2 * sm + 1];
                double x3r = x[i0 + 3 * sm];
                double x3i = x[i0 + 3 * sm + 1];
                double t0r = x0r + x2r;
                double t0i = x0i + x2i;
                double t1r = x0r - x2r;
                double t1i = x0i - x2i;
                double t2r = x1r + x3r;
                double t2i = x1i + x3i;
                // (x1 - x3)·(-i) forward, ·(+i) inverse
                double t3r = sg * (x1i - x3i);
                double t3i = -sg * (x1r - x3r);
                int o = b0 + q;
                y[o] = t0r + t2r;
                y[o + 1] = t0i + t2i;
                double yr = t1r + t3r;
                double yi = t1i + t3i;
                y[o + bs] = yr * w1r - yi * w1i;
                y[o + bs + 1] = yr * w1i + yi * w1r;
                yr = t0r - t2r;
                yi = t0i - t2i;
                y[o + 2 * bs] = yr * w2r - yi * w2i;
                y[o + 2 * bs + 1] = yr * w2i + yi * w2r;
                yr = t1r - t3r;
                yi = t1i - t3i;
                y[o + 3 * bs] = yr * w3r - yi * w3i;
                y[o + 3 * bs + 1] = yr * w3i + yi * w3r;
            }
        }
    }

    private void radix3(double[] x, int xo, double[] y, int yo, int m, int stride, double[] tw, double sg) {
        int sm = 2 * stride * m;
        double s3 = sg * c3;
        for (int p = 0; p < m; p++) {
            int t = 4 * p;
            double w1r = tw[t];
            double w1i = sg * tw[t + 1];
            double w2r = tw[t + 2];
            double w2i = sg * tw[t + 3];
            int a0 = xo + 2 * stride * p;
            int b0 = yo + 2 * stride * 3 * p;
            int bs = 2 * stride;
            for (int q = 0; q < 2 * stride; q += 2) {
                int i0 = a0 + q;
                double x0r = x[i0];
                double x0i = x[i0 + 1];
                double x1r = x[i0 + sm];
                double x1i = x[i0 + sm + 1];
                double x2r = x[i0 + 2 * sm];
                double x2i = x[i0 + 2 * sm + 1];
                double t1r = x1r + x2r;
                double t1i = x1i + x2i;
                double t2r = x0r - 0.5 * t1r;
                double t2i = x0i - 0.5 * t1i;
                double t3r = s3 * (x1r - x2r);
                double t3i = s3 * (x1i - x2i);
                int o = b0 + q;
                y[o] = x0r + t1r;
                y[o + 1] = x0i + t1i;
                // y1 = t2 - i·t3, y2 = t2 + i·t3
                double yr = t2r + t3i;
                double yi = t2i - t3r;
                y[o + bs] = yr * w1r - yi * w1i;
                y[o + bs + 1] = yr * w1i + yi * w1r;
                yr = t2r - t3i;
                yi = t2i + t3r;
                y[o + 2 * bs] = yr * w2r - yi * w2i;
                y[o + 2 * bs + 1] = yr * w2i + yi * w2r;
            }
        }
    }

    private void radix5(double[] x, int xo, double[] y, int yo, int m, int stride, double[] tw, double sg) {
        int sm = 2 * stride * m;
        double s1 = sg * s51;
        double s2 = sg * s52;
        for (int p = 0; p < m; p++) {
            int t = 8 * p;
            int a0 = xo + 2 * stride * p;
            int b0 = yo + 2 * stride * 5 * p;
            int bs = 2 * stride;
            for (int q = 0; q < 2 * stride; q += 2) {
                int i0 = a0 + q;
                double x0r = x[i0];
                double x0i = x[i0 + 1];
                double x1r = x[i0 + sm];
                double x1i = x[i0 + sm + 1];
                double x2r = x[i0 + 2 * sm];
                double x2i = x[i0 + 2 * sm + 1];
                double x3r = x[i0 + 3 * sm];
                double x3i = x[i0 + 3 * sm + 1];
                double x4r = x[i0 + 4 * sm];
                double x4i = x[i0 + 4 * sm + 1];
                double b1r = x1r + x4r;
                double b1i = x1i + x4i;
                double b2r = x2r + x3r;
                double b2i = x2i + x3i;
                double d1r = x1r - x4r;
                double d1i = x1i - x4i;
                double d2r = x2r - x3r;
                double d2i = x2i - x3i;
                double r1r = x0r + c51 * b1r + c52 * b2r;
                double r1i = x0i + c51 * b1i + c52 * b2i;
                double r2r = x0r + c52 * b1r + c51 * b2r;
                double r2i = x0i + c52 * b1i + c51 * b2i;
                double i1r = s1 * d1r + s2 * d2r;
                double i1i = s1 * d1i + s2 * d2i;
                double i2r = s2 * d1r - s1 * d2r;
                double i2i = s2 * d1i - s1 * d2i;
                int o = b0 + q;
                y[o] = x0r + b1r + b2r;
                y[o + 1] = x0i + b1i + b2i;
                // y1 = r1 - i·i1, y4 = r1 + i·i1, y2 = r2 - i·i2, y3 = r2 + i·i2
                store(y, o + bs, r1r + i1i, r1i - i1r, tw, t, sg);
                store(y, o + 2 * bs, r2r + i2i, r2i - i2r, tw, t + 2, sg);
                store(y, o + 3 * bs, r2r - i2i, r2i + i2r, tw, t + 4, sg);
                store(y, o + 4 * bs, r1r - i1i, r1i + i1r, tw, t + 6, sg);
            }
        }
    }

    private static void store(double[] y, int o, double yr, double yi, double[] tw, int t, double sg) {
        double wr = tw[t];
        double wi = sg * tw[t + 1];
        y[o] = yr * wr - yi * wi;
        y[o + 1] = yr * wi + yi * wr;
    }

    /** A direct butterfly for an odd prime radix, using {@code 4p} doubles of scratch at {@code temp}. */
    private static void radixP(double[] x, int xo, double[] y, int yo, int r, int m, int stride, double[] tw,
            double[] roots, double sg, double[] s, int temp) {
        int sm = 2 * stride * m;
        int h = (r - 1) / 2;
        int bsum = temp;          // b_k = x_k + x_(r-k), k = 1..h
        int bdif = temp + 2 * r;  // d_k = x_k - x_(r-k)
        for (int p = 0; p < m; p++) {
            int t = 2 * (r - 1) * p;
            int a0 = xo + 2 * stride * p;
            int b0 = yo + 2 * stride * r * p;
            int bs = 2 * stride;
            for (int q = 0; q < 2 * stride; q += 2) {
                int i0 = a0 + q;
                double x0r = x[i0];
                double x0i = x[i0 + 1];
                double sumr = x0r;
                double sumi = x0i;
                for (int k = 1; k <= h; k++) {
                    int ik = i0 + k * sm;
                    int il = i0 + (r - k) * sm;
                    double br = x[ik] + x[il];
                    double bi = x[ik + 1] + x[il + 1];
                    s[bsum + 2 * k] = br;
                    s[bsum + 2 * k + 1] = bi;
                    s[bdif + 2 * k] = x[ik] - x[il];
                    s[bdif + 2 * k + 1] = x[ik + 1] - x[il + 1];
                    sumr += br;
                    sumi += bi;
                }
                int o = b0 + q;
                y[o] = sumr;
                y[o + 1] = sumi;
                for (int j = 1; j <= h; j++) {
                    // root^(jk) = cos(2π jk/r) - i sin(2π jk/r)
                    double rr = x0r;
                    double ri = x0i;
                    double ir = 0.0;
                    double ii = 0.0;
                    int e = 0;
                    for (int k = 1; k <= h; k++) {
                        e += j;
                        if (e >= r) {
                            e -= r;
                        }
                        double c = roots[2 * e];
                        double sn = -sg * roots[2 * e + 1];
                        rr += c * s[bsum + 2 * k];
                        ri += c * s[bsum + 2 * k + 1];
                        ir += sn * s[bdif + 2 * k];
                        ii += sn * s[bdif + 2 * k + 1];
                    }
                    // y_j = R - i·I, y_(r-j) = R + i·I
                    store(y, o + j * bs, rr + ii, ri - ir, tw, t + 2 * (j - 1), sg);
                    store(y, o + (r - j) * bs, rr - ii, ri + ir, tw, t + 2 * (r - j - 1), sg);
                }
            }
        }
    }
}
