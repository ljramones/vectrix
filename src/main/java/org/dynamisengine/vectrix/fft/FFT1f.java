package org.dynamisengine.vectrix.fft;

/**
 * In-place radix-2 1D FFT over interleaved complex arrays:
 * {@code data[2*i]} = real, {@code data[2*i+1]} = imaginary. The forward transform is unscaled; the inverse divides
 * by {@code n}.
 * <p>
 * For other sizes, real input, caller-owned scratch, {@link java.lang.foreign.MemorySegment} data and the fastest
 * transforms, use {@link ComplexFftf} and {@link RealFftf}.
 * <p>
 * The twiddle factors come from an exactly reduced table shared by all threads. It is immutable, built on the
 * first transform of a larger size than any before, and reused for every smaller one, so a transform allocates
 * only then. Before 2.5.0 the twiddles were generated by a recurrence (carried in double), whose error grew with
 * the size.
 *
 * @since 1.0.0
 *
 * @deprecated use the planned transforms {@link ComplexFftf} and {@link RealFftf}: any size, faster, and allocation-free with caller scratch
 */
@Deprecated(since = "2.6.0", forRemoval = true)
public final class FFT1f {

    /** {@code exp(-2πi k/N)} for {@code k < N/2}, interleaved, for the largest size {@code N} so far. */
    private static volatile Table table = new Table(new float[0]);

    /** Publishes the table through a final field: the array is fully written before any thread can see it. */
    private static final class Table {
        final float[] values;

        Table(float[] values) {
            this.values = values;
        }
    }

    private FFT1f() {
    }

    public static void forward(float[] data) {
        transform(data, false);
    }

    public static void inverse(float[] data) {
        transform(data, true);
    }

    public static boolean isPowerOfTwoSize(int complexCount) {
        return complexCount > 0 && (complexCount & (complexCount - 1)) == 0;
    }

    private static float[] table(int n) {
        Table t = table;
        if (t.values.length < n) { // holds N/2 complex values: N floats
            t = new Table(FftMath.toFloat(FftMath.roots(n / 2, n)));
            table = t;
        }
        return t.values;
    }

    static void transform(float[] data, boolean inverse) {
        if (data == null || (data.length & 1) != 0) {
            throw new IllegalArgumentException("data");
        }
        int n = data.length >>> 1;
        if (!isPowerOfTwoSize(n)) {
            throw new IllegalArgumentException("complex length must be power-of-two");
        }
        if (n == 1) {
            return;
        }
        float[] tw = table(n);
        int big = tw.length; // N: the table holds the N/2 values exp(-2πi k/N), k < N/2

        int j = 0;
        for (int i = 0; i < n; i++) {
            if (i < j) {
                swapComplex(data, i, j);
            }
            int bit = n >>> 1;
            while ((j & bit) != 0) {
                j ^= bit;
                bit >>>= 1;
            }
            j ^= bit;
        }

        float sg = inverse ? -1.0f : 1.0f;
        for (int len = 2; len <= n; len <<= 1) {
            int half = len >>> 1;
            int step = big / len; // W_len^k = W_N^(k·N/len)
            for (int k = 0; k < half; k++) {
                float wR = tw[2 * k * step];
                float wI = sg * tw[2 * k * step + 1];
                for (int i = k; i < n; i += len) {
                    int uo = i << 1;
                    int vo = (i + half) << 1;
                    float vr = data[vo];
                    float vi = data[vo + 1];
                    float tr = wR * vr - wI * vi;
                    float ti = wR * vi + wI * vr;
                    float ur = data[uo];
                    float ui = data[uo + 1];
                    data[uo] = ur + tr;
                    data[uo + 1] = ui + ti;
                    data[vo] = ur - tr;
                    data[vo + 1] = ui - ti;
                }
            }
        }

        if (inverse) {
            float invN = 1.0f / n; // a power of two: exact
            for (int i = 0; i < data.length; i++) {
                data[i] *= invN;
            }
        }
    }

    private static void swapComplex(float[] data, int a, int b) {
        int ao = a << 1;
        int bo = b << 1;
        float tr = data[ao];
        float ti = data[ao + 1];
        data[ao] = data[bo];
        data[ao + 1] = data[bo + 1];
        data[bo] = tr;
        data[bo + 1] = ti;
    }
}
