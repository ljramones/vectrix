    /** Adds the last {@code r < 8} elements of a block to lanes 0..r-1, then combines the lanes. */
    private static double tail(double a0, double a1, double a2, double a3, double a4, double a5, double a6, double a7, MemorySegment x, long xo, MemorySegment y, long yo, long from, int r,
            int op, double s) {
        if (r > 0) {
            a0 = step(op, a0, x.getAtIndex(E, xo + from + 0), y == null ? 0 : y.getAtIndex(E, yo + from + 0), s);
        }
        if (r > 1) {
            a1 = step(op, a1, x.getAtIndex(E, xo + from + 1), y == null ? 0 : y.getAtIndex(E, yo + from + 1), s);
        }
        if (r > 2) {
            a2 = step(op, a2, x.getAtIndex(E, xo + from + 2), y == null ? 0 : y.getAtIndex(E, yo + from + 2), s);
        }
        if (r > 3) {
            a3 = step(op, a3, x.getAtIndex(E, xo + from + 3), y == null ? 0 : y.getAtIndex(E, yo + from + 3), s);
        }
        if (r > 4) {
            a4 = step(op, a4, x.getAtIndex(E, xo + from + 4), y == null ? 0 : y.getAtIndex(E, yo + from + 4), s);
        }
        if (r > 5) {
            a5 = step(op, a5, x.getAtIndex(E, xo + from + 5), y == null ? 0 : y.getAtIndex(E, yo + from + 5), s);
        }
        if (r > 6) {
            a6 = step(op, a6, x.getAtIndex(E, xo + from + 6), y == null ? 0 : y.getAtIndex(E, yo + from + 6), s);
        }
        if (r > 7) {
            a7 = step(op, a7, x.getAtIndex(E, xo + from + 7), y == null ? 0 : y.getAtIndex(E, yo + from + 7), s);
        }
        return ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7));
    }

    private static double step(int op, double a, double xv, double yv, double s) {
        switch (op) {
            case 0: return Math.fma(xv, yv, a);
            case 1: return a + xv;
            case 2: return a + Math.abs(xv);
            case 3: return Math.fma(xv, xv, a);
            default: return Math.fma(xv * s, xv * s, a);
        }
    }

