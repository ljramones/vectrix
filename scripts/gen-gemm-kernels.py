#!/usr/bin/env python3
"""Generates org.dynamisengine.vectrix.blas.Gemmf and Gemmd: matrix products in the dot-product formulation.

Usage (the second argument is the MIT license header to prepend):
    python3 scripts/gen-gemm-kernels.py src/main/java/org/dynamisengine/vectrix/blas header.txt

Every element of op(A)·op(B) is defined as Blasf/Blasd.dot of a row of op(A) and a column of op(B), in that class's
documented order (256-element blocks of 8 fused-multiply-add lanes, combined pairwise). The scalar path calls the dot
kernel per element; the Vector API path computes an MR x NR tile of those dot products at once, from operands packed
so rows and columns are contiguous along k, and reduces the 8 lanes with three shift-and-add steps that reproduce the
fixed lane tree. Both give the same bits.
"""
import os
import sys

CFG = {
    'float': dict(B='Float', V='FloatVector', MR=4, NR=2, VMAX=2, cls='Gemmf', blas='Blasf', z='0.0f',
                  sp='SPECIES_256', twin='Gemmd'),
    'double': dict(B='Double', V='DoubleVector', MR=2, NR=2, VMAX=4, cls='Gemmd', blas='Blasd', z='0.0',
                   sp='SPECIES_512', twin='Gemmf'),
}


def gen(T, header):
    c = CFG[T]
    B, V, MR, NR, VMAX, cls, blas, z = c['B'], c['V'], c['MR'], c['NR'], c['VMAX'], c['cls'], c['blas'], c['z']
    o = []
    w = o.append
    w(header)
    w(f'''package org.dynamisengine.vectrix.blas;

//#ifdef __HAS_VECTOR_API__
import jdk.incubator.vector.{V};
import jdk.incubator.vector.VectorShuffle;
import jdk.incubator.vector.VectorSpecies;
import org.dynamisengine.vectrix.simd.SimdSupport;
//#endif

/**
 * Matrix products over row-major {T} arrays: {{@link #gemm}} ({{@code C = α·op(A)·op(B) + β·C}}) and {{@link #gemv}}
 * ({{@code y = α·op(A)·x + β·y}}), with {{@code op(X)}} either {{@code X}} or its transpose; the twin of
 * {{@link {c['twin']}}}. Generated by {{@code scripts/gen-gemm-kernels.py}}: edit the generator, not this file.
 * <p>
 * <b>Definition.</b> Each element of {{@code op(A)·op(B)}} is exactly {{@link {blas}#dot}} of a row of {{@code op(A)}}
 * and a column of {{@code op(B)}}, in that class's documented order, so a matrix product, a matrix-vector product
 * and a dot product of the same data agree bit for bit (a batch of one gives the same result as a batch of many),
 * on every platform and with or without the Vector API. The error per element is that of the dot product, about
 * {{@code (32 + log2(k/256))·ε·Σ|a·b|}}. The result is then {{@code α·s}} when {{@code β == 0}} ({{@code C}} is not
 * read, so it may hold NaN), and {{@code fma(α, s, β·c)}} otherwise.
 * <p>
 * <b>Performance.</b> The Vector API path computes {MR}×{NR} tiles of dot products at once from operands packed into
 * caller scratch ({{@link #scratchSize}}), so the layouts that are already contiguous along {{@code k}}
 * ({{@code A}} not transposed, {{@code B}} transposed, as in {{@code x·Wᵀ}}) need the least packing. Calls do not
 * allocate and are single-threaded; to parallelize, give threads disjoint row ranges of {{@code C}} (each with its
 * own scratch): the results do not depend on the split.
 *
 * @since 2.5.0
 */
public final class {cls} {{

    /** Columns of {{@code op(B)}} packed per panel. */
    static final int NC = 64;

    /** Rows of {{@code op(A)}} packed per panel when {{@code A}} is transposed. */
    static final int MC = 64;

    /** Recursion slots for the pairwise tile sums (blocks of 256 up to 2^31 elements need at most 24). */
    private static final int DEPTH = 26;

    private static final int MR = {MR};

    private static final int NR = {NR};

    private {cls}() {{
    }}

    /**
     * The scratch {{@link #gemm}} needs.
     *
     * @return the number of {T}s
     */
    public static int scratchSize(boolean transA, boolean transB, int m, int n, int k) {{
        if (m < 0 || n < 0 || k < 0) {{
            throw new IllegalArgumentException("negative size: " + m + ", " + n + ", " + k);
        }}
        long s = (long) DEPTH * MR * NR;
        if (!transB) {{
            s += (long) Math.min(NC, n) * k;
        }}
        if (transA) {{
            s += (long) Math.min(MC, m) * k;
        }}
        if (s > Integer.MAX_VALUE - 8) {{
            throw new IllegalArgumentException("k too large for the packing panels: " + k);
        }}
        return (int) s;
    }}

    /**
     * {{@code C = α·op(A)·op(B) + β·C}}, where {{@code op(A)}} is {{@code m×k}}, {{@code op(B)}} is {{@code k×n}} and
     * {{@code C}} is {{@code m×n}}, all row-major with leading dimensions (row strides) {{@code lda}}, {{@code ldb}},
     * {{@code ldc}}. {{@code C}} must not overlap {{@code A}} or {{@code B}}.
     *
     * @param scratch at least {{@link #scratchSize}} {T}s from {{@code scratchOff}}, overwritten
     */
    public static void gemm(boolean transA, boolean transB, int m, int n, int k, {T} alpha, {T}[] a, int aOff,
            int lda, {T}[] b, int bOff, int ldb, {T} beta, {T}[] c, int cOff, int ldc, {T}[] scratch,
            int scratchOff) {{
        if (m < 0 || n < 0 || k < 0) {{
            throw new IllegalArgumentException("negative size: " + m + ", " + n + ", " + k);
        }}
        matrix(a, aOff, lda, transA ? k : m, transA ? m : k, "a");
        matrix(b, bOff, ldb, transB ? n : k, transB ? k : n, "b");
        matrix(c, cOff, ldc, m, n, "c");
        int need = scratchSize(transA, transB, m, n, k);
        if (scratch == null || scratchOff < 0 || scratchOff > scratch.length - need) {{
            throw new IllegalArgumentException("scratch must hold " + need + " values from offset " + scratchOff);
        }}
        if (m == 0 || n == 0) {{
            return;
        }}
        int slots = scratchOff;
        int bPack = slots + DEPTH * MR * NR;
        int aPack = bPack + (transB ? 0 : Math.min(NC, n) * k);
        boolean simd = false;
//#ifdef __HAS_VECTOR_API__
        simd = Simd.ON && Simd.enabled() && k >= 8;
//#endif
        for (int j0 = 0; j0 < n; j0 += NC) {{
            int nb = Math.min(NC, n - j0);
            // columns of op(B) contiguous along k: B transposed is already; otherwise pack them
            {T}[] bs;
            int bBase;
            int bStride;
            if (transB) {{
                bs = b;
                bBase = bOff + j0 * ldb;
                bStride = ldb;
            }} else {{
                for (int kk = 0; kk < k; kk++) {{
                    int row = bOff + kk * ldb + j0;
                    for (int jj = 0; jj < nb; jj++) {{
                        scratch[bPack + jj * k + kk] = b[row + jj];
                    }}
                }}
                bs = scratch;
                bBase = bPack;
                bStride = k;
            }}
            for (int i0 = 0; i0 < m; i0 += MC) {{
                int mb = Math.min(MC, m - i0);
                {T}[] as;
                int aBase;
                int aStride;
                if (!transA) {{
                    as = a;
                    aBase = aOff + i0 * lda;
                    aStride = lda;
                }} else {{
                    for (int kk = 0; kk < k; kk++) {{
                        int row = aOff + kk * lda + i0;
                        for (int ii = 0; ii < mb; ii++) {{
                            scratch[aPack + ii * k + kk] = a[row + ii];
                        }}
                    }}
                    as = scratch;
                    aBase = aPack;
                    aStride = k;
                }}
                panel(as, aBase, aStride, mb, bs, bBase, bStride, nb, k, alpha, beta, c, cOff + i0 * ldc + j0, ldc,
                        scratch, slots, simd);
            }}
        }}
    }}

    /**
     * {{@code y = α·op(A)·x + β·y}}, where {{@code op(A)}} is {{@code m×n}} ({{@code A}} itself is {{@code n×m}} when
     * transposed). Each element is {{@link {blas}#dot}} of a row of {{@code op(A)}} with {{@code x}}, as in
     * {{@link #gemm}}. {{@code y}} must not overlap {{@code A}} or {{@code x}}.
     *
     * @param scratch at least {{@code n}} {T}s when {{@code A}} is transposed (unused otherwise; may be null)
     */
    public static void gemv(boolean transA, int m, int n, {T} alpha, {T}[] a, int aOff, int lda, {T}[] x, int xOff,
            {T} beta, {T}[] y, int yOff, {T}[] scratch, int scratchOff) {{
        if (m < 0 || n < 0) {{
            throw new IllegalArgumentException("negative size: " + m + ", " + n);
        }}
        matrix(a, aOff, lda, transA ? n : m, transA ? m : n, "a");
        matrix(x, xOff, n, 1, n, "x");
        matrix(y, yOff, m, 1, m, "y");
        if (transA && n > 0 && (scratch == null || scratchOff < 0 || scratchOff > scratch.length - n)) {{
            throw new IllegalArgumentException("scratch must hold " + n + " values from offset " + scratchOff);
        }}
        for (int i = 0; i < m; i++) {{
            {T} s;
            if (n == 0) {{
                s = {z};
            }} else if (!transA) {{
                s = {blas}.dot(a, aOff + i * lda, x, xOff, n);
            }} else {{
                for (int kk = 0; kk < n; kk++) {{
                    scratch[scratchOff + kk] = a[aOff + kk * lda + i];
                }}
                s = {blas}.dot(scratch, scratchOff, x, xOff, n);
            }}
            y[yOff + i] = finish(alpha, s, beta, y[yOff + i]);
        }}
    }}

    private static {T} finish({T} alpha, {T} s, {T} beta, {T} c) {{
        return beta == 0 ? alpha * s : Math.fma(alpha, s, beta * c);
    }}

    /** One packed panel: whole tiles on the vector path, the rest as single dot products. */
    private static void panel({T}[] as, int aBase, int aStride, int mb, {T}[] bs, int bBase, int bStride, int nb,
            int k, {T} alpha, {T} beta, {T}[] c, int cBase, int ldc, {T}[] scratch, int slots, boolean simd) {{
        int iEnd = simd ? mb - mb % MR : 0;
        int jEnd = simd ? nb - nb % NR : 0;
        for (int i = 0; i < mb; i++) {{
            for (int j = 0; j < nb; j++) {{
                if (i < iEnd && j < jEnd) {{
                    continue;
                }}
                {T} s = k == 0 ? {z} : {blas}.dot(as, aBase + i * aStride, bs, bBase + j * bStride, k);
                int ci = cBase + i * ldc + j;
                c[ci] = finish(alpha, s, beta, c[ci]);
            }}
        }}
//#ifdef __HAS_VECTOR_API__
        for (int i = 0; i < iEnd; i += MR) {{
            for (int j = 0; j < jEnd; j += NR) {{
                Simd.tile(as, aBase + i * aStride, aStride, bs, bBase + j * bStride, bStride, 0, k, scratch, slots);
                for (int r = 0; r < MR; r++) {{
                    for (int q = 0; q < NR; q++) {{
                        int ci = cBase + (i + r) * ldc + j + q;
                        c[ci] = finish(alpha, scratch[slots + r * NR + q], beta, c[ci]);
                    }}
                }}
            }}
        }}
//#endif
    }}

    private static void matrix({T}[] x, int off, int ld, int rows, int cols, String name) {{
        if (rows == 0 || cols == 0) {{
            return;
        }}
        if (x == null || off < 0 || ld < cols || off > x.length - ((long) (rows - 1) * ld + cols)) {{
            throw new IllegalArgumentException(name + ": " + rows + "x" + cols + " with leading dimension " + ld
                    + " does not fit from offset " + off);
        }}
    }}
''')
    w(simd(T, c))
    w('}\n')
    return '\n'.join(o)


def simd(T, c):
    B, V, MR, NR, VMAX, z = c['B'], c['V'], c['MR'], c['NR'], c['VMAX'], c['z']
    o = []
    w = o.append
    w(f'''    /**
     * Vector API tiles. Each output's 8 logical lanes live on {{@code VEC}} vectors; a full block collapses them with
     * shift-and-add steps that compute ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7)) exactly.
     */
    private static final class Simd {{
//#ifdef __HAS_VECTOR_API__
        static final VectorSpecies<{B}> S = pick();
        static final int LANES = S.length();
        static final int VEC = 8 / LANES;
        static final boolean ON = SimdSupport.isVectorApiAvailable() && LANES >= 2 && 8 % LANES == 0
                && VEC <= {VMAX};
        static final VectorShuffle<{B}> HALF = VectorShuffle.fromOp(S, i -> (i + LANES / 2) % LANES);

        private Simd() {{
        }}

        static boolean enabled() {{
            return SimdSupport.backend() == SimdSupport.Backend.VECTOR_API;
        }}

        private static VectorSpecies<{B}> pick() {{
            VectorSpecies<{B}> p = {V}.SPECIES_PREFERRED;
            return p.length() > 8 ? {V}.{c['sp']} : p;
        }}

        /**
         * The {MR}×{NR} dot products of rows {{@code a + r·as}} and columns {{@code b + q·bs}} over {{@code [lo, hi)}},
         * written to {{@code scratch[slot .. slot + {MR * NR})}} in the pairwise block order.
         */
        static void tile({T}[] a, int ao, int as, {T}[] b, int bo, int bs, int lo, int hi, {T}[] scratch, int slot) {{
            if (hi - lo <= {c['blas']}.BLOCK) {{
                leaf(a, ao, as, b, bo, bs, lo, hi - lo, scratch, slot);
                return;
            }}
            int blocks = (hi - lo + {c['blas']}.BLOCK - 1) / {c['blas']}.BLOCK;
            int mid = lo + (blocks + 1) / 2 * {c['blas']}.BLOCK;
            int next = slot + {MR * NR};
            tile(a, ao, as, b, bo, bs, lo, mid, scratch, next);
            System.arraycopy(scratch, next, scratch, slot, {MR * NR});
            tile(a, ao, as, b, bo, bs, mid, hi, scratch, next);
            for (int t = 0; t < {MR * NR}; t++) {{
                scratch[slot + t] = scratch[slot + t] + scratch[next + t];
            }}
        }}
''')
    # leaf
    names = [(r, q) for r in range(MR) for q in range(NR)]
    w(f'''        private static void leaf({T}[] a, int ao, int as, {T}[] b, int bo, int bs, int lo, int len, {T}[] scratch,
                int slot) {{''')
    for (r, q) in names:
        for v in range(VMAX):
            w(f'            {V} c{r}{q}v{v} = {V}.zero(S);')
    w('            int full = len & ~7;')
    w('            for (int i = 0; i < full; i += 8) {')
    w('                int k = lo + i;')
    for v in range(VMAX):
        ind = '                ' if v == 0 else '                    '
        if v > 0:
            w(f'                if (VEC > {v}) {{')
        for r in range(MR):
            w(f'{ind}{V} a{r}v{v} = {V}.fromArray(S, a, ao + {r} * as + k + {v} * LANES);')
        for q in range(NR):
            w(f'{ind}{V} b{q}v{v} = {V}.fromArray(S, b, bo + {q} * bs + k + {v} * LANES);')
        for (r, q) in names:
            w(f'{ind}c{r}{q}v{v} = a{r}v{v}.fma(b{q}v{v}, c{r}{q}v{v});')
        if v > 0:
            w('                }')
    w('            }')
    w('            if (full != len) {')
    w('                // the last block of a k that is not a multiple of 8: the lanes as scalars (constant indices,')
    w('                // so nothing is boxed), the remaining products added to lanes 0..rest-1, then the tree')
    w('                int k = lo + full;')
    w('                int rest = len - full;')
    for idx, (r, q) in enumerate(names):
        cv = [f'c{r}{q}v{v}' for v in range(VMAX)]
        w('                {')
        for l in range(8):
            w(f'                    {T} l{l};')
        cases = [(1, lambda t: f'{cv[0]}.lane({t})')]
        cases.append((2, lambda t: f'{cv[t // 4]}.lane({t % 4})'))
        if VMAX >= 4:
            cases.append((4, lambda t: f'{cv[t // 2]}.lane({t % 2})'))
        first = True
        for vec, fn in reversed(cases):
            if vec == 1:
                w('                    } else {')
            else:
                w(f'                    {"if" if first else "} else if"} (VEC == {vec}) {{')
            first = False
            for t in range(8):
                w(f'                        l{t} = {fn(t)};')
        w('                    }')
        for t in range(8):
            w(f'                    if (rest > {t}) {{')
            w(f'                        l{t} = Math.fma(a[ao + {r} * as + k + {t}], b[bo + {q} * bs + k + {t}], l{t});')
            w('                    }')
        w(f'                    scratch[slot + {idx}] = ((l0 + l4) + (l2 + l6)) + ((l1 + l5) + (l3 + l7));')
        w('                }')
    w('                return;')
    w('            }')
    # collapse inline (a call taking vectors would box them): ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7))
    for idx, (r, q) in enumerate(names):
        cv = [f'c{r}{q}v{v}' for v in range(VMAX)]
        tree = '(p.lane(0) + p.lane(2)) + (p.lane(1) + p.lane(3))'
        w('            {')
        if VMAX >= 4:
            w('                if (VEC == 4) { // (a0, a1), (a2, a3), (a4, a5), (a6, a7)')
            w(f'                    {V} p = {cv[0]}.add({cv[2]}).add({cv[1]}.add({cv[3]}));')
            w(f'                    scratch[slot + {idx}] = p.lane(0) + p.lane(1);')
            w('                } else if (VEC == 2) { // (a0..a3), (a4..a7)')
        else:
            w('                if (VEC == 2) { // (a0..a3), (a4..a7)')
        w(f'                    {V} p = {cv[0]}.add({cv[1]});')
        w(f'                    scratch[slot + {idx}] = {tree};')
        w('                } else { // one 8-lane vector: lanes 0..3 become (a0 + a4, a1 + a5, a2 + a6, a3 + a7)')
        w(f'                    {V} p = {cv[0]}.add({cv[0]}.rearrange(HALF));')
        w(f'                    scratch[slot + {idx}] = {tree};')
        w('                }')
        w('            }')
    w('        }')
    w('''//#else
        static final boolean ON = false;

        private Simd() {
        }
//#endif
    }''')
    return '\n'.join(o)


if __name__ == '__main__':
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from javadoc_overlay import overlay
    target, header = sys.argv[1], open(sys.argv[2]).read().rstrip('\n')
    for T in ('float', 'double'):
        path = f'{target}/{CFG[T]["cls"]}.java'
        text = overlay(gen(T, header), path)  # read the existing docs before the file is truncated
        open(path, 'w').write(text)
