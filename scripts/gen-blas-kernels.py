#!/usr/bin/env python3
"""Generates org.dynamisengine.vectrix.blas.Blasf and Blasd: BLAS-1 kernels with a deterministic reduction order.

Usage (the second argument is the MIT license header to prepend):
    python3 scripts/gen-blas-kernels.py src/main/java/org/dynamisengine/vectrix/blas header.txt

Every reduction has one definition, which the scalar and Vector API paths both implement exactly:
  - the input is cut into blocks of 256 elements (the last may be shorter);
  - within a block, logical lane l (0..7) accumulates the elements whose index in the block is l mod 8, in order,
    with fused multiply-adds or additions;
  - a block's value is ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7));
  - blocks combine pairwise: sum(lo, hi) = sum(lo, mid) + sum(mid, hi), mid = lo + (hi - lo + 1) / 2.
The SIMD path maps the 8 logical lanes onto 1, 2 or 4 vectors and uses lanewise fma/add, which round exactly like the
scalar Math.fma and +, so both paths, every vector width and every platform give the same bits.
"""
import os
import sys

# per reduction: (name, has y, scalar step, vector step, javadoc)
#   scalar step: expression of the new accumulator from 'a', 'xv', 'yv' (and 's' for scaled)
#   vector step: expression of the new accumulator vector from 'acc', 'X', 'Y' (and 'S')
REDUCTIONS = [
    ('dot', True, 'Math.fma(xv, yv, a)', 'X.fma(Y, acc)'),
    ('sum', False, 'a + xv', 'acc.add(X)'),
    ('asum', False, 'a + Math.abs(xv)', 'acc.add(X.abs())'),
    ('sumSq', False, 'Math.fma(xv, xv, a)', 'X.fma(X, acc)'),
    ('sumSqScaled', False, 'Math.fma(xv * s, xv * s, a)', 'X.mul(S).fma(X.mul(S), acc)'),
]


def gen(T):
    B = 'Float' if T == 'float' else 'Double'
    V = B + 'Vector'
    L = 'JAVA_FLOAT_UNALIGNED' if T == 'float' else 'JAVA_DOUBLE_UNALIGNED'
    size = 4 if T == 'float' else 8
    cls = 'Blasf' if T == 'float' else 'Blasd'
    twin = 'Blasd' if T == 'float' else 'Blasf'
    z = '0.0f' if T == 'float' else '0.0'
    out = []
    w = out.append
    w(HEADER_TEXT)
    w(f'''package org.dynamisengine.vectrix.blas;

import java.lang.foreign.MemorySegment;
import java.lang.foreign.ValueLayout;
//#ifdef __HAS_VECTOR_API__
import java.nio.ByteOrder;
import jdk.incubator.vector.{V};
import jdk.incubator.vector.VectorSpecies;
import org.dynamisengine.vectrix.simd.SimdSupport;
//#endif

/**
 * BLAS level-1 kernels over {T} arrays and {{@link MemorySegment}}s, with a deterministic reduction order; the twin
 * of {{@link {twin}}}. Generated by {{@code scripts/gen-blas-kernels.py}}: edit the generator, not this file.
 * <p>
 * <b>Reductions</b> ({{@link #dot}}, {{@link #sum}}, {{@link #asum}}, {{@link #nrm2}}) have one fixed evaluation
 * order: blocks of 256 elements, each summed in 8 interleaved lanes (lane {{@code l}} takes the elements whose index
 * in the block is {{@code l mod 8}}) combined as {{@code ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7))}}, and
 * the blocks summed pairwise. The scalar and Vector API ({{@code -simd}} jar) paths implement exactly this order
 * with fused multiply-adds, so a reduction gives the same bits on every platform, vector width and jar. A caller
 * that splits a long reduction across threads reproduces it exactly by splitting at the pairwise midpoints (whole
 * blocks, the first half rounded up) and adding the two halves. The error is at most about
 * {{@code (32 + log2(n/256))·ε·Σ|terms|}}, against {{@code n·ε}} for a plain loop.
 * <p>
 * <b>Element-wise</b> kernels ({{@link #axpy}}, {{@link #scal}}) round each element once ({{@code axpy}} uses a
 * fused multiply-add). Arrays and segments of the same values give the same results. Segments hold native-order
 * values at element offsets; nothing allocates, and every method is safe to call from any number of threads on
 * disjoint outputs.
 *
 * @since 2.5.0
 */
public final class {cls} {{

    /** The reduction block length. */
    public static final int BLOCK = 256;

    private static final ValueLayout.Of{B} E = ValueLayout.{L};

    private {cls}() {{
    }}
''')
    # ---------- public API ----------
    for kind in ('array', 'segment'):
        A = f'{T}[]' if kind == 'array' else 'MemorySegment'
        I = 'int' if kind == 'array' else 'long'
        w(f'''
    /**
     * The dot product {{@code Σ x[i]·y[i]}}.
     *
     * @param n the number of elements, {{@code >= 0}}
     * @return the dot product (0 for {{@code n == 0}})
     */
    public static {T} dot({A} x, {I} xOff, {A} y, {I} yOff, {I} n) {{
        check(x, xOff, n, "x");
        check(y, yOff, n, "y");
        return n == 0 ? {z} : dotPairwise(x, xOff, y, yOff, 0, n);
    }}

    /** The sum {{@code Σ x[i]}}. */
    public static {T} sum({A} x, {I} xOff, {I} n) {{
        check(x, xOff, n, "x");
        return n == 0 ? {z} : sumPairwise(x, xOff, 0, n);
    }}

    /** The sum of magnitudes {{@code Σ |x[i]|}}. */
    public static {T} asum({A} x, {I} xOff, {I} n) {{
        check(x, xOff, n, "x");
        return n == 0 ? {z} : asumPairwise(x, xOff, 0, n);
    }}

    /**
     * The Euclidean norm {{@code sqrt(Σ x[i]²)}}, without overflow or underflow: when the plain sum of squares is not
     * a normal number, it is recomputed with the elements scaled by a power of two (exactly).
     */
    public static {T} nrm2({A} x, {I} xOff, {I} n) {{
        check(x, xOff, n, "x");
        if (n == 0) {{
            return {z};
        }}
        {T} s = sumSqPairwise(x, xOff, 0, n, ({T}) 1);
        if (s >= {B}.MIN_NORMAL && s < {B}.POSITIVE_INFINITY) {{
            return ({T}) Math.sqrt(s);
        }}
        if (s != s) {{
            return s; // NaN in, NaN out
        }}
        {T} m = {z};
        for ({I} i = 0; i < n; i++) {{
            m = Math.max(m, Math.abs({get('x', 'xOff + i', kind)}));
        }}
        if (m == {z} || m == {B}.POSITIVE_INFINITY) {{
            return m;
        }}
        int e = Math.getExponent(m);
        {T} scale = Math.scalb(({T}) 1, -e);
        {T} t = sumSqScaledPairwise(x, xOff, 0, n, scale);
        return Math.scalb(({T}) Math.sqrt(t), e);
    }}

    /** {{@code y[i] = fma(a, x[i], y[i])}}. {{@code x}} and {{@code y}} may be the same at the same offset. */
    public static void axpy({T} a, {A} x, {I} xOff, {A} y, {I} yOff, {I} n) {{
        check(x, xOff, n, "x");
        check(y, yOff, n, "y");
        {I} i = 0;
//#ifdef __HAS_VECTOR_API__
        if (Simd.ON && Simd.enabled()) {{
            i = Simd.axpy(a, x, xOff, y, yOff, n);
        }}
//#endif
        for (; i < n; i++) {{
            {put('y', 'yOff + i', f'Math.fma(a, {get("x", "xOff + i", kind)}, {get("y", "yOff + i", kind)})', kind)}
        }}
    }}

    /** {{@code x[i] = a·x[i]}}. */
    public static void scal({T} a, {A} x, {I} xOff, {I} n) {{
        check(x, xOff, n, "x");
        {I} i = 0;
//#ifdef __HAS_VECTOR_API__
        if (Simd.ON && Simd.enabled()) {{
            i = Simd.scal(a, x, xOff, n);
        }}
//#endif
        for (; i < n; i++) {{
            {put('x', 'xOff + i', f'a * {get("x", "xOff + i", kind)}', kind)}
        }}
    }}

    /** The index of the first element of largest magnitude ({{@code -1}} for {{@code n == 0}}; NaN counts as largest). */
    public static {I} iamax({A} x, {I} xOff, {I} n) {{
        check(x, xOff, n, "x");
        {I} best = -1;
        {T} m = -1;
        for ({I} i = 0; i < n; i++) {{
            {T} v = Math.abs({get('x', 'xOff + i', kind)});
            if (v > m || v != v) {{
                best = i;
                m = v;
                if (v != v) {{
                    break;
                }}
            }}
        }}
        return best;
    }}
''')
        # pairwise recursions and leaves
        for name, hasy, sstep, vstep in REDUCTIONS:
            args = f'{A} x, {I} xo' + (f', {A} y, {I} yo' if hasy else '')
            call = 'x, xo' + (', y, yo' if hasy else '')
            extra = f', {T} s' if name == 'sumSqScaled' else ''
            ecall = ', s' if name == 'sumSqScaled' else ''
            if name == 'sumSq':
                extra, ecall = f', {T} s', ''  # unused scale keeps one signature for nrm2
            w(f'''
    private static {T} {name}Pairwise({args}, {I} lo, {I} hi{extra}) {{
        if (hi - lo <= BLOCK) {{
//#ifdef __HAS_VECTOR_API__
            if (Simd.ON && Simd.enabled()) {{
                return Simd.{name}Block({call}, lo, (int) (hi - lo){ecall});
            }}
//#endif
            return {name}Block({call}, lo, (int) (hi - lo){ecall});
        }}
        {I} blocks = (hi - lo + BLOCK - 1) / BLOCK;
        {I} mid = lo + (blocks + 1) / 2 * BLOCK;
        return {name}Pairwise({call}, lo, mid{', s' if extra else ''}) + {name}Pairwise({call}, mid, hi{', s' if extra else ''});
    }}

    private static {T} {name}Block({args}, {I} lo, int len{(', ' + T + ' s') if name == 'sumSqScaled' else ''}) {{
        {T} a0 = {z};
        {T} a1 = {z};
        {T} a2 = {z};
        {T} a3 = {z};
        {T} a4 = {z};
        {T} a5 = {z};
        {T} a6 = {z};
        {T} a7 = {z};
        int full = len & ~7;
        for (int i = 0; i < full; i += 8) {{''')
            for l in range(8):
                xv = get('x', f'xo + lo + i + {l}', kind)
                yv = get('y', f'yo + lo + i + {l}', kind) if hasy else None
                step = sstep.replace('xv', xv).replace('a)', f'a{l})').replace('a +', f'a{l} +')
                if hasy:
                    step = step.replace('yv', yv)
                w(f'            a{l} = {step};')
            yargs = 'y, yo' if hasy else 'null, 0'
            sarg = 's' if name == 'sumSqScaled' else f'({T}) 1'
            w(f'''        }}
        return tail(a0, a1, a2, a3, a4, a5, a6, a7, x, xo, {yargs}, lo + full, len - full, {RIDX[name]}, {sarg});
    }}''')
        # tail helper: finishes lanes l < r with the remaining elements, then the fixed tree
        w(f'''
    /** Adds the last {{@code r < 8}} elements of a block to lanes 0..r-1, then combines the lanes. */
    private static {T} tail({', '.join(f'{T} a{l}' for l in range(8))}, {A} x, {I} xo, {A} y, {I} yo, {I} from, int r,
            int op, {T} s) {{''')
        for l in range(8):
            w(f'''        if (r > {l}) {{
            a{l} = step(op, a{l}, {get('x', f'xo + from + {l}', kind)}, y == null ? 0 : {get('y', f'yo + from + {l}', kind)}, s);
        }}''')
        w(f'''        return ((a0 + a4) + (a2 + a6)) + ((a1 + a5) + (a3 + a7));
    }}''')
    # common step for tails
    w(f'''
    private static {T} step(int op, {T} a, {T} xv, {T} yv, {T} s) {{
        switch (op) {{
            case 0: return Math.fma(xv, yv, a);
            case 1: return a + xv;
            case 2: return a + Math.abs(xv);
            case 3: return Math.fma(xv, xv, a);
            default: return Math.fma(xv * s, xv * s, a);
        }}
    }}

    private static void check({T}[] a, int off, int n, String name) {{
        if (a == null || n < 0 || off < 0 || off > a.length - n) {{
            throw new IllegalArgumentException(name + " must hold " + n + " values from offset " + off);
        }}
    }}

    private static void check(MemorySegment a, long off, long n, String name) {{
        if (a == null || n < 0 || off < 0 || off > a.byteSize() / {size} - n) {{
            throw new IllegalArgumentException(name + " must hold " + n + " values from offset " + off);
        }}
    }}
''')
    w(simd_class(T, B, V, L, size, z))
    w('}\n')
    return '\n'.join(out)


RIDX = {'dot': 0, 'sum': 1, 'asum': 2, 'sumSq': 3, 'sumSqScaled': 4}


def get(arr, idx, kind):
    if kind == 'array':
        return f'{arr}[{idx}]'
    return f'{arr}.getAtIndex(E, {idx})'


def put(arr, idx, val, kind):
    if kind == 'array':
        return f'{arr}[{idx}] = {val};'
    return f'{arr}.setAtIndex(E, {idx}, {val});'


def simd_class(T, B, V, L, size, z):
    o = []
    w = o.append
    w(f'''
    /**
     * Vector API kernels: the 8 logical lanes of a block on 1, 2 or 4 vectors, with the scalar path's operations.
     * Kept in a holder so the scalar build never loads {{@code jdk.incubator.vector}}.
     */
    private static final class Simd {{
//#ifdef __HAS_VECTOR_API__
        static final VectorSpecies<{B}> S = pick();
        static final int LANES = S.length();
        static final boolean ON = SimdSupport.isVectorApiAvailable() && LANES >= 2 && 8 % LANES == 0;
        static final int VEC = 8 / LANES;

        private Simd() {{
        }}

        static boolean enabled() {{
            return SimdSupport.backend() == SimdSupport.Backend.VECTOR_API;
        }}

        private static VectorSpecies<{B}> pick() {{
            VectorSpecies<{B}> p = {V}.SPECIES_PREFERRED;
            return p.length() > 8 ? {V}.{'SPECIES_256' if T == 'float' else 'SPECIES_512'} : p;
        }}
''')
    for kind in ('array', 'segment'):
        A = f'{T}[]' if kind == 'array' else 'MemorySegment'
        I = 'int' if kind == 'array' else 'long'

        def load(arr, idx):
            if kind == 'array':
                return f'{V}.fromArray(S, {arr}, {idx})'
            return f'{V}.fromMemorySegment(S, {arr}, ({idx}) * {size}L, ByteOrder.nativeOrder())'

        def store(vec, arr, idx):
            if kind == 'array':
                return f'{vec}.intoArray({arr}, {idx});'
            return f'{vec}.intoMemorySegment({arr}, ({idx}) * {size}L, ByteOrder.nativeOrder());'

        for name, hasy, sstep, vstep in REDUCTIONS:
            args = f'{A} x, {I} xo' + (f', {A} y, {I} yo' if hasy else '')
            sp = f', {T} s' if name == 'sumSqScaled' else ''
            w(f'''
        static {T} {name}Block({args}, {I} lo, int len{sp}) {{''')
            if name == 'sumSqScaled':
                w(f'            {V} sv = {V}.broadcast(S, s);')
            w(f'''            {V} c0 = {V}.zero(S);
            {V} c1 = {V}.zero(S);
            {V} c2 = {V}.zero(S);
            {V} c3 = {V}.zero(S);
            int full = len & ~7;
            for (int i = 0; i < full; i += 8) {{''')
            for t in range(4):
                if t == 1:
                    w('                if (VEC > 1) {')
                if t == 2:
                    w('                if (VEC > 2) {')
                ind = '                    ' if t > 0 else '                '
                X = load('x', f'xo + lo + i + {t} * LANES')
                Y = load('y', f'yo + lo + i + {t} * LANES') if hasy else None
                step = vstep.replace('acc', f'c{t}').replace('X', f'x{t}').replace('S)', 'sv)')
                if hasy:
                    step = step.replace('Y', f'y{t}')
                w(f'{ind}{V} x{t} = {X};')
                if hasy:
                    w(f'{ind}{V} y{t} = {Y};')
                w(f'{ind}c{t} = {step};')
                if t == 1:
                    w('                }')
                if t == 3:
                    w('                }')
            w(f'''            }}
            // logical lane l is lane (l mod LANES) of vector (l / LANES)
            {T} a0 = lane(c0, c1, c2, c3, 0);
            {T} a1 = lane(c0, c1, c2, c3, 1);
            {T} a2 = lane(c0, c1, c2, c3, 2);
            {T} a3 = lane(c0, c1, c2, c3, 3);
            {T} a4 = lane(c0, c1, c2, c3, 4);
            {T} a5 = lane(c0, c1, c2, c3, 5);
            {T} a6 = lane(c0, c1, c2, c3, 6);
            {T} a7 = lane(c0, c1, c2, c3, 7);
            return tail(a0, a1, a2, a3, a4, a5, a6, a7, x, xo, {'y, yo' if hasy else 'null, 0'}, lo + full, len - full,
                    {RIDX[name]}, {'s' if name == 'sumSqScaled' else '(' + T + ') 1'});
        }}''')
        w(f'''
        static {I} axpy({T} a, {A} x, {I} xo, {A} y, {I} yo, {I} n) {{
            {V} av = {V}.broadcast(S, a);
            {I} bound = n - n % LANES;
            for ({I} i = 0; i < bound; i += LANES) {{
                {V} r = av.fma({load('x', 'xo + i')}, {load('y', 'yo + i')});
                {store('r', 'y', 'yo + i')}
            }}
            return bound;
        }}

        static {I} scal({T} a, {A} x, {I} xo, {I} n) {{
            {I} bound = n - n % LANES;
            for ({I} i = 0; i < bound; i += LANES) {{
                {V} r = {load('x', 'xo + i')}.mul(a);
                {store('r', 'x', 'xo + i')}
            }}
            return bound;
        }}''')
    w(f'''
        private static {T} lane({V} c0, {V} c1, {V} c2, {V} c3, int l) {{
            int v = l / LANES;
            int k = l % LANES;
            {V} c = v == 0 ? c0 : v == 1 ? c1 : v == 2 ? c2 : c3;
            return c.lane(k);
        }}
//#else
        static final boolean ON = false;

        private Simd() {{
        }}
//#endif
    }}''')
    return '\n'.join(o)


if __name__ == '__main__':
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from javadoc_overlay import overlay
    target = sys.argv[1]
    HEADER_TEXT = open(sys.argv[2]).read().rstrip('\n') if len(sys.argv) > 2 else ''
    for T in ('float', 'double'):
        src = gen(T)
        name = 'Blasf.java' if T == 'float' else 'Blasd.java'
        path = os.path.join(target, name)
        text = overlay(src, path)  # read the existing docs before the file is truncated
        open(path, 'w').write(text)
